/** Record<type, nome traduzido>. Tipo desconhecido devolve undefined,
 *  igual ao objeto literal de antes. */
export const ENEMY_NAMES: Record<string, string> = Object.defineProperties(
  {},
  Object.fromEntries(
    ENEMY_TYPES.map(type => [type, {
      enumerable: true,
      get: () => t(`enemy.${type}.name`),
    }]),
  ),
) as Record<string, string>;
// Heroi Corrompido (Etapa 3b): "{{hero}} Corrompido" com o nome curto do heroi (ui.class.*)
for (const h of HEROIS_CORROMPIVEIS) Object.defineProperty(ENEMY_NAMES, `corrupted_${h}`, {
  enumerable: true,
  get: () => t('enemy.corrupted.name', { hero: t(`ui.class.${h}`) }),
});

// ---------------------------------------------------------------------------
// Bestiário
// ---------------------------------------------------------------------------

function entry(type: string, threat: ThreatLevel, hp: StatKey, dmg: StatKey, speed: StatKey): BestiaryEntry {
  return {
    type,
    threat,
    get name()      { return t(`bestiary.${type}.name`);  },
    get title()     { return t(`bestiary.${type}.title`); },
    get wave()      { return t(`bestiary.${type}.wave`);  },
    get lore()      { return t(`bestiary.${type}.lore`);  },
    get abilities() { return tList(`bestiary.${type}.ability`); },
    get hp()        { return t(`stat.${hp}`);    },
    get dmg()       { return t(`stat.${dmg}`);   },
    get speed()     { return t(`stat.${speed}`); },
  };
}

